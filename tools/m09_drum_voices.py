# GM notes 36..51. Reused templates still sound at the incoming note pitch.
NOTE_TEMPLATE_KEYS = (
    "kick", "stick", "snare", "clap", "snare", "tom", "closed_hat", "tom",
    "closed_hat", "tom", "open_hat", "tom", "tom", "cymbal", "tom", "cymbal",
)


def build_runtime_templates() -> tuple[bytes, bytes]:
    index_by_key = {template.key: index for index, template in enumerate(TEMPLATES)}
    runtime = bytearray()
    for template in TEMPLATES:
        packed = template.packed()
        if sha256(packed).hexdigest() != template.voice_sha256:
            raise ValueError(f"DX7 voice hash mismatch for {template.key}")
        if voice_name(packed).strip() == "":
            raise ValueError(f"empty DX7 voice name for {template.key}")
        runtime.extend(unpack_voice(packed))
    note_map = bytes(index_by_key[key] for key in NOTE_TEMPLATE_KEYS)
    if len(runtime) != len(TEMPLATES) * RUNTIME_VOICE_SIZE:
        raise AssertionError("unexpected runtime template size")
    return bytes(runtime), note_map
